#!/usr/bin/env python3
"""Generate vectors.S for the Xtensa self-test: computational instructions with operands
from a fixed-seed generator (edge values included) and the results this script's model of
the ISA manual's definitions gives. The self-test runs each and compares.

    python3 -I gen_vectors.py OUT.S

Each vector is a macro call (selftest.S defines the macros):
    T_RRR  op, a, b, expected            ar = op(as, at)
    T_RR   op, a, expected               ar = op(at)        (NEG, ABS, NSA, NSAU: as/at per op)
    T_RRI  op, a, imm, expected          at/ar = op(as, imm)
    T_SAR  op, sarsetup, a, b, expected  shift through SAR
Vectors for options a model lacks are inside #if guards (model.h's XT_HAVE_*).
"""
import random
import sys

M = 0xFFFFFFFF
rnd = random.Random(0x5EED)
EDGE = [0, 1, 2, 0x7FFFFFFF, 0x80000000, 0x80000001, 0xFFFFFFFF, 0xFFFFFFFE, 0x0000FFFF,
        0x00008000, 0x00007FFF, 0xFFFF8000, 0x12345678, 0x87654321, 0x55555555, 0xAAAAAAAA]


def s32(x):
    x &= M
    return x - (1 << 32) if x >> 31 else x


def sext(x, b):
    x &= (1 << b) - 1
    return x - (1 << b) if x >> (b - 1) else x


def vals(n):
    out = list(EDGE)
    while len(out) < n:
        k = rnd.randrange(4)
        if k == 0:
            out.append(rnd.getrandbits(32))
        elif k == 1:
            out.append(rnd.getrandbits(8))
        elif k == 2:
            out.append((-rnd.getrandbits(16)) & M)
        else:
            out.append(1 << rnd.randrange(32))
    return out


def pairs(n):
    a, b = vals(n), vals(n)
    rnd.shuffle(b)
    return list(zip(a, b))


def clz(x):
    return 32 - x.bit_length() if x else 32


def nsa(x):
    x &= M
    if x >> 31:
        x = ~x & M
    return clz(x) - 1 if x else 31


def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


RRR = {
    "add": lambda a, b: a + b,
    "sub": lambda a, b: a - b,
    "addx2": lambda a, b: (a << 1) + b,
    "addx4": lambda a, b: (a << 2) + b,
    "addx8": lambda a, b: (a << 3) + b,
    "subx2": lambda a, b: (a << 1) - b,
    "subx4": lambda a, b: (a << 2) - b,
    "subx8": lambda a, b: (a << 3) - b,
    "and": lambda a, b: a & b,
    "or": lambda a, b: a | b,
    "xor": lambda a, b: a ^ b,
    "mul16u": lambda a, b: (a & 0xFFFF) * (b & 0xFFFF),
    "mul16s": lambda a, b: sext(a, 16) * sext(b, 16),
    "mull": lambda a, b: a * b,
}
GUARDED = {   # op: (guard, fn)
    "muluh": ("XT_HAVE_MUL32_HIGH", lambda a, b: (a * b) >> 32),
    "mulsh": ("XT_HAVE_MUL32_HIGH", lambda a, b: (s32(a) * s32(b)) >> 32),
    "min": ("XT_HAVE_MINMAX", lambda a, b: min(s32(a), s32(b))),
    "max": ("XT_HAVE_MINMAX", lambda a, b: max(s32(a), s32(b))),
    "minu": ("XT_HAVE_MINMAX", lambda a, b: min(a, b)),
    "maxu": ("XT_HAVE_MINMAX", lambda a, b: max(a, b)),
    "salt": ("XT_HAVE_SALT", lambda a, b: int(s32(a) < s32(b))),
    "saltu": ("XT_HAVE_SALT", lambda a, b: int(a < b)),
}
DIV = {
    "quou": lambda a, b: a // b,
    "remu": lambda a, b: a % b,
    "quos": lambda a, b: tdiv(s32(a), s32(b)) if not (s32(a) == -2**31 and s32(b) == -1) else -2**31,
    "rems": lambda a, b: s32(a) - s32(b) * tdiv(s32(a), s32(b)) if not (s32(a) == -2**31 and s32(b) == -1) else 0,
}


def main():
    out = []
    w = out.append
    w("/* Generated by gen_vectors.py: do not edit. */")
    w("    .text")
    w("    .align 4")
    w("    .global run_vectors")
    w("run_vectors:")
    w("    ENTER_FN")
    for op, fn in RRR.items():
        for a, b in pairs(24):
            w("    T_RRR %s, 0x%08x, 0x%08x, 0x%08x" % (op, a, b, fn(a, b) & M))
    for op, (g, fn) in GUARDED.items():
        w("#if %s" % g)
        for a, b in pairs(24):
            w("    T_RRR %s, 0x%08x, 0x%08x, 0x%08x" % (op, a, b, fn(a, b) & M))
        w("#endif")
    w("#if XT_HAVE_DIV32")
    for op, fn in DIV.items():
        for a, b in pairs(24) + [(0x80000000, 0xFFFFFFFF)]:
            if b == 0:
                b = 7
            w("    T_RRR %s, 0x%08x, 0x%08x, 0x%08x" % (op, a, b, fn(a, b) & M))
    w("#endif")
    for a in vals(20):
        w("    T_NEG 0x%08x, 0x%08x" % (a, -a & M))
        w("    T_ABS 0x%08x, 0x%08x" % (a, abs(s32(a)) & M))
        w("    T_NSAU 0x%08x, 0x%08x" % (a, clz(a)))
        w("    T_NSA 0x%08x, 0x%08x" % (a, nsa(a)))
    w("#if XT_HAVE_SEXT")
    for a in vals(12):
        for n in (7, 8, 15, 22, rnd.randrange(7, 23)):
            w("    T_RRI sext, 0x%08x, %d, 0x%08x" % (a, n, sext(a, n + 1) & M))
    w("#endif")
    w("#if XT_HAVE_CLAMPS")
    for a in vals(12):
        for n in (7, 8, 15, 22, rnd.randrange(7, 23)):
            v = max(-(1 << n), min((1 << n) - 1, s32(a)))
            w("    T_RRI clamps, 0x%08x, %d, 0x%08x" % (a, n, v & M))
    w("#endif")
    for a in vals(12):
        for sa in (0, 1, 15, 31, rnd.randrange(32)):
            for bits in (1, 16, rnd.randrange(1, 17)):
                if sa + bits > 32:
                    continue
                w("    T_EXTUI 0x%08x, %d, %d, 0x%08x" % (a, sa, bits, (a >> sa) & ((1 << bits) - 1)))
        for sh in (1, 2, 16, 31, rnd.randrange(1, 32)):
            w("    T_RRI slli, 0x%08x, %d, 0x%08x" % (a, sh, (a << sh) & M))
            w("    T_RRI srai, 0x%08x, %d, 0x%08x" % (a, sh, (s32(a) >> sh) & M))
        for sh in (0, 1, 15, rnd.randrange(16)):
            w("    T_RRI srli, 0x%08x, %d, 0x%08x" % (a, sh, a >> sh))
        for k in (-128, -1, 0, 1, 127, rnd.randrange(-128, 128)):
            w("    T_RRI addi, 0x%08x, %d, 0x%08x" % (a, k, (a + k) & M))
        for k in (-128, -1, 1, 127):
            w("    T_RRI addmi, 0x%08x, %d, 0x%08x" % (a, k * 256, (a + k * 256) & M))
    # shifts through SAR: SSR (right), SSL (left), SSA8L/SSA8B, SSAI, and SAR = 32
    for a, b in pairs(16):
        for n in (0, 1, 8, 31, rnd.randrange(32)):
            w("    T_SRC ssr, %d, 0x%08x, 0x%08x, 0x%08x" % (n, a, b, (((a << 32) | b) >> n) & M))
            w("    T_SRL ssr, %d, 0x%08x, 0x%08x" % (n, b, b >> n))
            w("    T_SRA ssr, %d, 0x%08x, 0x%08x" % (n, b, (s32(b) >> n) & M))
            w("    T_SLL ssl, %d, 0x%08x, 0x%08x" % (n, a, (a << (n % 32)) & M if n % 32 else a))
        for n in (0, 1, 2, 3, 7):
            w("    T_SRC ssa8l, %d, 0x%08x, 0x%08x, 0x%08x" % (n, a, b, (((a << 32) | b) >> ((n & 3) * 8)) & M))
            sar = 32 - (n & 3) * 8
            w("    T_SRC ssa8b, %d, 0x%08x, 0x%08x, 0x%08x" % (n, a, b, (((a << 32) | b) >> sar) & M))
    w("    LEAVE_FN")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
