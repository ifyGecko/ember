#!/usr/bin/env python3
"""Arithmetic test vectors for the 8051 self-test.

Each vector is eight bytes: op, a, b, psw_in, res_a, res_b, psw_out, check, run by the
self-test as A = a, R2 (or B) = b, PSW = psw_in, then the instruction `op`; `check`
says what it compares (bit 0 A, bit 1 B, bit 2 P; CY, AC and OV always). The expected
values come from the MCS-51 instruction set's definitions worked bit by bit - a ripple
adder and subtractor whose carries and borrows give CY, AC and OV as the manual words
them ("a carry out of bit 6 but not out of bit 7..."), and DA A's two adjustments - so
they share nothing with the lifter's arithmetic.

usage: gen_vectors.py OUT.asm
"""
import sys

OPS = ["ADD", "ADDC", "SUBB", "DA", "MUL", "DIV", "RLC", "RRC", "CJNE"]
CY, AC, OV, P = 0x80, 0x40, 0x04, 0x01


def parity(x):
    return bin(x).count("1") & 1


def ripple(a, b, cin, sub):
    """a + b + cin or a - b - cin bit by bit: (result, carry/borrow out of each bit)."""
    r, c, outs = 0, cin, []
    for i in range(8):
        x, y = (a >> i) & 1, (b >> i) & 1
        if sub:
            d = x - y - c
            bit, c = d & 1, 1 if d < 0 else 0
        else:
            s = x + y + c
            bit, c = s & 1, s >> 1
        r |= bit << i
        outs.append(c)
    return r, outs


def run(op, a, b, pin):
    """(res_a, res_b, psw_out, check)."""
    cy = 1 if pin & CY else 0
    psw = pin & (CY | AC | OV)
    if op in ("ADD", "ADDC", "SUBB"):
        r, c = ripple(a, b, cy if op != "ADD" else 0, op == "SUBB")
        psw = (CY if c[7] else 0) | (AC if c[3] else 0) | (OV if c[6] != c[7] else 0)
        return r, b, psw | parity(r), 7
    if op == "DA":
        r, ac = a, pin & AC
        if (r & 0xF) > 9 or ac:
            r += 6
            if r > 0xFF:
                cy = 1
            r &= 0xFF
        if (r >> 4) > 9 or cy:
            r += 0x60
            if r > 0xFF:
                cy = 1
            r &= 0xFF
        psw = (pin & (AC | OV)) | (CY if cy else 0)
        return r, b, psw | parity(r), 7
    if op == "MUL":
        p = a * b
        return p & 0xFF, p >> 8, (OV if p > 0xFF else 0) | parity(p & 0xFF), 7
    if op == "DIV":
        if b == 0:   # A and B undefined; OV set
            return a, b, OV, 0
        q, m = divmod(a, b)
        return q, m, parity(q), 7
    if op in ("RLC", "RRC"):
        if op == "RLC":
            r, out = ((a << 1) | cy) & 0xFF, a >> 7
        else:
            r, out = (a >> 1) | (cy << 7), a & 1
        return r, b, (pin & (AC | OV)) | (CY if out else 0) | parity(r), 7
    if op == "CJNE":
        return a, b, (pin & (AC | OV)) | (CY if a < b else 0) | parity(a), 7
    raise ValueError(op)


def main():
    vals = [0x00, 0x01, 0x09, 0x0F, 0x10, 0x55, 0x7F, 0x80, 0x81, 0x99, 0xFF]
    pins = [0x00, CY, AC, CY | AC]
    rows = []
    for k, op in enumerate(OPS):
        if op == "DA":
            cases = [(a, 0, p) for a in range(256) for p in pins]
        elif op in ("MUL", "DIV"):
            cases = [(a, b, CY | OV) for a in vals for b in vals]
        elif op in ("RLC", "RRC"):
            cases = [(a, 0, p) for a in vals for p in (0, CY | OV)]
        elif op == "CJNE":
            cases = [(a, b, p) for a in vals for b in vals for p in (0, CY)]
        else:
            cases = [(a, b, p) for a in vals for b in vals for p in pins]
        for a, b, p in cases:
            ra, rb, pout, chk = run(op, a, b, p)
            rows.append((k, a, b, p, ra, rb, pout, chk))
    with open(sys.argv[1], "w") as fp:
        fp.write("; generated by gen_vectors.py: do not edit\n")
        fp.write("; ops: " + " ".join("%d %s" % (k, o) for k, o in enumerate(OPS)) + "\n")
        fp.write("vectab:\n")
        for row in rows:
            fp.write("        .db " + ", ".join("0x%02x" % v for v in row) + "\n")
        fp.write("        .db 0xff\n")


if __name__ == "__main__":
    main()
