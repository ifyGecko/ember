#!/usr/bin/env python3
"""Status-register test vectors for the AVR self-test.

Each vector is (op, a, b, sreg_in, result, sreg_out): the instruction `op` applied to
registers holding a and b, with SREG = sreg_in before it. The expected flags come from
the boolean equations the AVR Instruction Set Manual gives for each instruction, written
out bit by bit as the manual does, so they do not share the lifter's arithmetic.

usage: gen_vectors.py OUT.h [full|medium|small]   (the sizes fit 256, 32 and 4 KiB devices)
"""
import sys

OPS = ["ADD", "ADC", "SUB", "SBC", "AND", "OR", "EOR", "COM", "NEG", "INC", "DEC",
       "LSR", "ROR", "ASR", "CP", "CPC"]
C, Z, N, V, S, H = 0, 1, 2, 3, 4, 5


def b(x, n):
    return (x >> n) & 1


def run(op, d, r, sin):
    """The result (or None for compares) and SREG bits 0-5 after `op`."""
    cin, zin, hin = b(sin, C), b(sin, Z), b(sin, H)
    f = {C: cin, Z: zin, N: b(sin, N), V: b(sin, V), S: b(sin, S), H: hin}
    write = op not in ("CP", "CPC")
    if op in ("ADD", "ADC"):
        R = (d + r + (cin if op == "ADC" else 0)) & 0xFF
        f[H] = (b(d, 3) & b(r, 3)) | (b(r, 3) & (1 - b(R, 3))) | ((1 - b(R, 3)) & b(d, 3))
        f[V] = (b(d, 7) & b(r, 7) & (1 - b(R, 7))) | ((1 - b(d, 7)) & (1 - b(r, 7)) & b(R, 7))
        f[C] = (b(d, 7) & b(r, 7)) | (b(r, 7) & (1 - b(R, 7))) | ((1 - b(R, 7)) & b(d, 7))
        f[Z] = int(R == 0)
    elif op in ("SUB", "SBC", "CP", "CPC"):
        withc = op in ("SBC", "CPC")
        R = (d - r - (cin if withc else 0)) & 0xFF
        f[H] = ((1 - b(d, 3)) & b(r, 3)) | (b(r, 3) & b(R, 3)) | (b(R, 3) & (1 - b(d, 3)))
        f[V] = (b(d, 7) & (1 - b(r, 7)) & (1 - b(R, 7))) | ((1 - b(d, 7)) & b(r, 7) & b(R, 7))
        f[C] = ((1 - b(d, 7)) & b(r, 7)) | (b(r, 7) & b(R, 7)) | (b(R, 7) & (1 - b(d, 7)))
        f[Z] = int(R == 0) & (zin if withc else 1)
    elif op in ("AND", "OR", "EOR"):
        R = {"AND": d & r, "OR": d | r, "EOR": d ^ r}[op]
        f[V] = 0
        f[Z] = int(R == 0)
    elif op == "COM":
        R = 0xFF - d
        f[V], f[C], f[Z] = 0, 1, int(R == 0)
    elif op == "NEG":
        R = (0 - d) & 0xFF
        f[H] = b(R, 3) | b(d, 3)
        f[V] = int(R == 0x80)
        f[C] = int(R != 0)
        f[Z] = int(R == 0)
    elif op == "INC":
        R = (d + 1) & 0xFF
        f[V], f[Z] = int(R == 0x80), int(R == 0)
    elif op == "DEC":
        R = (d - 1) & 0xFF
        f[V], f[Z] = int(R == 0x7F), int(R == 0)
    elif op in ("LSR", "ROR", "ASR"):
        top = {"LSR": 0, "ROR": cin, "ASR": b(d, 7)}[op]
        R = (top << 7) | (d >> 1)
        f[C], f[Z] = b(d, 0), int(R == 0)
        f[N] = b(R, 7)
        f[V] = f[N] ^ f[C]
    else:
        raise ValueError(op)
    if op not in ("LSR", "ROR", "ASR"):
        f[N] = b(R, 7)
    f[S] = f[N] ^ f[V]
    sout = sum(f[k] << k for k in f)
    return (R if write else d), sout


def main():
    out = sys.argv[1]
    size = sys.argv[2] if len(sys.argv) > 2 else "full"
    vals = {"full": [0x00, 0x01, 0x08, 0x0F, 0x10, 0x55, 0x7F, 0x80, 0x81, 0xFE, 0xFF],   # < 32 KiB
            "medium": [0x00, 0x01, 0x0F, 0x10, 0x7F, 0x80, 0xFE, 0xFF],
            "small": [0x00, 0x80, 0xFF]}[size]
    srs = [0x03] if size == "small" else [0x00, 0x01, 0x02, 0x23]
    unary = {"COM", "NEG", "INC", "DEC", "LSR", "ROR", "ASR"}
    rows = []
    for k, op in enumerate(OPS):
        for d in vals:
            for r in ([0] if op in unary else vals):
                for sin in srs:
                    res, sout = run(op, d, r, sin)
                    rows.append((k, d, r, sin, res, sout))
    with open(out, "w") as fp:
        fp.write("/* generated by gen_vectors.py: do not edit */\n")
        fp.write("enum {" + ", ".join("OP_" + o for o in OPS) + "};\n")
        fp.write("static const struct vec { uint8_t op, a, b, sin, res, sout; } VECS[] VEC_ATTR = {\n")
        for row in rows:
            fp.write("    {%d, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x},\n" % row)
        fp.write("};\n")


if __name__ == "__main__":
    main()
