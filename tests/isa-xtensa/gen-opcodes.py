#!/usr/bin/env python3
"""Generate isa/xtensa/xtensa_opc.h, the Xtensa decoder's opcode table, from opcodes.py.

opcodes.py is the encoding table: every instruction of the core and of the options the
GNU tools know for the LX106, LX6 (ESP32) and LX7 (ESP32-S2, ESP32-S3) cores, as fixed
bits over the little-endian instruction word, checked against those assemblers and
disassemblers (xt-check.py checks ember's decoder against the disassemblers directly).

    python3 -I -B tests/isa-xtensa/gen-opcodes.py > isa/xtensa/xtensa_opc.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import opcodes  # noqa: E402

# Option groups of opcodes.py -> the C enum the decoder maps to UAM_XT_OPT_* bits.
GROUPS = ["core", "density", "windowed", "loop", "boolean", "fp", "fp_ext", "mac16",
          "mul16", "mul32", "mul32_high", "div32", "nsa", "minmax", "sext", "clamps",
          "s32c1i", "mp_sync", "exception", "interrupt", "debug", "tlb", "cache",
          "cache_lock", "cache_test", "salt", "s32nb", "sim"]


def cname(key):
    return "XTO_" + key.upper().replace(".", "_").replace("@", "_")


def main():
    ents = [e for e in opcodes.OPCODES if not e.get("variant")]
    # The returns ignore their s field, as the GNU tools' tables (generated from the
    # cores' ISA descriptions) decode them.
    for e in ents:
        if e["mn"] in ("ret", "retw", "ret.n", "retw.n"):
            e["fixed"] = {f: v for f, v in e["fixed"].items() if f != "s"}
            e["mask"], e["value"] = opcodes.match(e)
    for e in ents:
        assert e["opt"] in GROUPS, e["opt"]
    # AR operand fields (for the window-overflow check): r = 4, s = 2, t = 1
    def arf(e):
        v = 0
        for op in e["ops"]:
            if op[1] == "a" and len(op) > 2:
                v |= {"r": 4, "s": 2, "t": 1}[op[2]]
        return v
    ents.sort(key=lambda e: (e["value"] & 15, e["len"], -bin(e["mask"]).count("1"), e["key"]))
    out = []
    w = out.append
    w("/* xtensa_opc.h - Xtensa opcode table (decoder input).")
    w(" * Generated by tests/isa-xtensa/gen-opcodes.py from tests/isa-xtensa/opcodes.py:")
    w(" * do not edit. Fixed bits are over the little-endian instruction word (a big-endian")
    w(" * word is rearranged to it first, xt_be_to_le). */")
    w("#ifndef UAM_XTENSA_OPC_H")
    w("#define UAM_XTENSA_OPC_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w("enum xt_group {")
    for g in GROUPS:
        w("    XTG_%s," % g.upper())
    w("};")
    w("")
    w("enum xt_opid {")
    for e in sorted(ents, key=lambda e: e["key"]):
        w("    %s," % cname(e["key"]))
    w("    XTO__COUNT")
    w("};")
    w("")
    w("typedef struct xt_opc {")
    w("    uint32_t mask, value;")
    w("    uint16_t id;      /* enum xt_opid */")
    w("    uint8_t  len;     /* bytes */")
    w("    uint8_t  group;   /* enum xt_group */")
    w("    uint8_t  arf;     /* fields naming address registers: r 4, s 2, t 1 */")
    w("} xt_opc;")
    w("")
    w("/* Sorted by op0, then length, then the most fixed bits first. */")
    w("static const xt_opc xt_opcodes[] = {")
    for e in ents:
        w("    { 0x%06x, 0x%06x, %s, %d, XTG_%s, %d },"
          % (e["mask"], e["value"], cname(e["key"]), e["len"], e["opt"].upper(), arf(e)))
    w("};")
    w("")
    w("static const char *const xt_opnames[XTO__COUNT] = {")
    for e in sorted(ents, key=lambda e: e["key"]):
        w('    [%s] = "%s",' % (cname(e["key"]), e["mn"]))
    w("};")
    w("")
    w("#endif /* UAM_XTENSA_OPC_H */")
    print("\n".join(out))


if __name__ == "__main__":
    main()
