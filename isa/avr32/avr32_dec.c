unsigned avr32_decode(uint32_t w)
{
    const bool compact = (w >> 29) != 7;
    for (unsigned i = 0; i < sizeof(dec_table) / sizeof(dec_table[0]); i++) {
        const uint32_t m = compact ? dec_table[i].mask & 0xFFFF0000u : dec_table[i].mask;
        if ((dec_table[i].value >> 29 != 7) == compact && (w & m) == dec_table[i].value)
            return dec_table[i].op;
    }
    return A32_ILLEGAL;
}
