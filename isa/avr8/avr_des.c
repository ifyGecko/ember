/* Bit table[i] (1-based, from the most significant of `in_bits`) of v, gathered. */
static uint64_t permute(uint64_t v, const uint8_t *table, unsigned n, unsigned in_bits)
{
    uint64_t r = 0;
    for (unsigned i = 0; i < n; i++)
        r = r << 1 | ((v >> (in_bits - table[i])) & 1);
    return r;
}

static uint64_t subkey(uint64_t key, unsigned round)
{
    uint64_t cd = permute(key, PC1, 56, 64);
    uint32_t c = (uint32_t)(cd >> 28) & 0xFFFFFFF, d = (uint32_t)cd & 0xFFFFFFF;
    for (unsigned r = 0; r <= round; r++)
        for (unsigned k = 0; k < SHIFTS[r]; k++) {
            c = ((c << 1) | (c >> 27)) & 0xFFFFFFF;
            d = ((d << 1) | (d >> 27)) & 0xFFFFFFF;
        }
    return permute((uint64_t)c << 28 | d, PC2, 48, 56);
}

static uint32_t f(uint32_t r, uint64_t k)
{
    uint64_t x = permute(r, E, 48, 32) ^ k;
    uint32_t out = 0;
    for (unsigned i = 0; i < 8; i++) {
        unsigned six = (unsigned)(x >> (42 - 6 * i)) & 0x3F;
        unsigned row = ((six >> 4) & 2) | (six & 1), col = (six >> 1) & 0xF;
        out = out << 4 | S[i][row * 16 + col];
    }
    return (uint32_t)permute(out, P, 32, 32);
}

static uint64_t get64(const uint8_t *r)
{
    uint64_t v = 0;
    for (int i = 7; i >= 0; i--)
        v = v << 8 | r[i];
    return v;
}

static void put64(uint8_t *r, uint64_t v)
{
    for (unsigned i = 0; i < 8; i++)
        r[i] = (uint8_t)(v >> (8 * i));
}

void avr_des_round(uint8_t regs[16], unsigned k, bool decrypt)
{
    uint64_t block = get64(regs);
    const uint64_t key = get64(regs + 8);
    if (k == 0)
        block = permute(block, IP, 64, 64);
    uint32_t l = (uint32_t)(block >> 32), r = (uint32_t)block;
    const uint32_t nl = r, nr = l ^ f(r, subkey(key, decrypt ? 15 - k : k));
    block = (uint64_t)nl << 32 | nr;
    if (k == 15)
        block = permute((uint64_t)nr << 32 | nl, FP, 64, 64);   /* the final swap, then FP */
    put64(regs, block);
}
